import fs from 'node:fs';
import vm from 'node:vm';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {parseHTML} from 'linkedom';
const sourceRoot=process.argv[2];
if(!sourceRoot)throw Error('Pass an extracted baseline checkout path; do not overwrite the baseline with upgraded content.');
const read=file=>fs.readFileSync(path.join(sourceRoot,file),'utf8');
const ctx = {window: {}};
vm.runInNewContext(read('assets/data/insights-articles.js'), ctx);
const articles = ctx.window.ELBOUBAKRY_INSIGHTS_ARTICLES;
const text = html => html.replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi,'').replace(/<[^>]*>/g,' ').replace(/&[^;]+;/g,' ').replace(/\s+/g,' ').trim();
const rows = articles.map(a => {
 const html = read(`insights/${a.slug}.html`);
 const document=parseHTML(html).document;
 const article=document.querySelector('.ea-article-content');
 if(!article)throw Error('Missing article body: '+a.slug);
 const body=article.innerHTML;
 const words=text(body).split(/\s+/).length;
 const sources=[...body.matchAll(/href="(https?:[^"#]+)"/g)].map(m=>m[1]).filter(x=>!x.includes('elboubakry.com'));
 const links=[...body.matchAll(/href="([^"]+)"/g)].map(m=>m[1]);
 const flags=[];
 if(words<500)flags.push('Short treatment: assess missing examples and task detail (word count is not a ranking rule)');
 if(!sources.length)flags.push('No external primary sources in article body');
 if(!/ea-article-author/.test(html))flags.push('Missing visible byline');
 if(!/ea-article-author[^>]*>[\s\S]*?<a\b/.test(html))flags.push('Byline not linked to profile');
 if(!/Mis à jour le/.test(html))flags.push('No explicit visible update date; do not refresh dates without substantive review');
 if(!/<time\b/.test(html))flags.push('Dates are plain text, without a semantic time element');
 if(links.filter(x=>x.includes('/insights/')).length<2)flags.push('Few contextual guide links (sidebar excluded)');
 return {slug:a.slug,url:`https://elboubakry.com/insights/${a.slug}`,title:a.title,category:a.category,bodyWords:words,hasVisibleUpdateDate:/Mis à jour le/.test(html),primarySources:sources,bodyLinks:links,headings:[...article.querySelectorAll('h2')].map(x=>x.textContent.trim()),flags,bodySha256:createHash('sha256').update(body).digest('hex')};
});
fs.mkdirSync('docs/upgrade',{recursive:true});
fs.writeFileSync('docs/upgrade/insights-audit-baseline.json',JSON.stringify({date:'2026-11-11',commit:'e64a68d4313604fae0eff9bb8b38a9eba7bb2016',scope:'All 30 French guides; source evidence, not Search Console traffic data',rows},null,2)+'\n');
console.log(JSON.stringify({guides:rows.length,under500Words:rows.filter(x=>x.bodyWords<500).length,withoutBodySources:rows.filter(x=>!x.primarySources.length).length,wordRange:[Math.min(...rows.map(x=>x.bodyWords)),Math.max(...rows.map(x=>x.bodyWords))],titles:rows.map(x=>[x.slug,x.bodyWords])},null,2));
