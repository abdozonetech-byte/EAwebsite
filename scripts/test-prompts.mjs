import assert from 'node:assert/strict';
import fs from 'node:fs';
import { prompts,categories,models } from '../assets/data/prompts.js';
import { validateCatalog,customize,readState,stateQuery,filterPrompts,readFavorites,saveFavorites,escapeHTML,FAVORITES_KEY,copyText } from '../assets/js/prompt-library-core.js';
import { card } from '../assets/js/prompt-library-render.js';
validateCatalog(prompts,categories,models);
assert.equal(prompts.length,16);assert.equal(categories.length,14);
assert.equal(new Set(prompts.map(p=>p.category)).size,14);
assert.throws(()=>validateCatalog([...prompts,prompts[0]],categories,models));
assert.equal(customize('[CITY] / [CITY] / [OTHER]',{CITY:'Rabat $& <b>',OTHER:''}),'Rabat $& <b> / Rabat $& <b> / [OTHER]');
assert.equal(customize('[CITY]',{CITY:'   '}),'[CITY]');
const original=prompts[0].prompt;customize(original,{PUBLIC:'test'});assert.equal(prompts[0].prompt,original);
let state=readState('?q=%C3%A9ducation&category=invalid&model=unknown&page=-1&sort=hack',prompts);
assert.equal(state.category,'');assert.equal(state.sort,'recommended');assert.equal(state.page,1);
assert(filterPrompts(prompts,{...state,q:'education'}).length>0);
assert(filterPrompts(prompts,{...state,q:'n8n'}).some(p=>p.category==='automation'));
assert(filterPrompts(prompts,{...state,q:'IA généraliste'},[],{},models).length>0);
assert.equal(filterPrompts(prompts,{...state,q:'zzz-no-such-prompt'}).length,0);
state=readState('?q=CRM&category=automation&model=chatgpt&level=intermediate&tag=CRM&sort=alpha&fav=1&page=2',prompts);
assert.deepEqual(readState(stateQuery(state),prompts),state);
assert.equal(filterPrompts(prompts,{...state,page:1},[]).length,0);
assert.equal(filterPrompts(prompts,{...state,page:1},['workflow-qualification-crm']).length,1);
const map=new Map(),storage={getItem:key=>map.get(key)||null,setItem:(key,value)=>map.set(key,value)};
assert(saveFavorites(storage,[prompts[0].id]));assert.deepEqual(readFavorites(storage,prompts),[prompts[0].id]);
storage.setItem(FAVORITES_KEY,JSON.stringify(['unknown',prompts[0].id,prompts[0].id]));assert.deepEqual(readFavorites(storage,prompts),[prompts[0].id]);
storage.setItem(FAVORITES_KEY,'broken-json');assert.deepEqual(readFavorites(storage,prompts),[]);
assert.deepEqual(readFavorites(null,prompts),[]);assert.equal(saveFavorites(null,[]),false);
assert.equal(escapeHTML('<script>"&'), '&lt;script&gt;&quot;&amp;');
let copied='',removed=false,selected=false;
const multiline='Line 1\n[TEXT] & <b> $& 😀',area={value:'',style:{},setAttribute(){},select(){selected=true;},remove(){removed=true;}};
const doc={createElement:()=>area,body:{append(){}},execCommand:()=>true};
assert(await copyText(multiline,{clipboard:{writeText:async text=>{copied=text;}},document:doc}));assert.equal(copied,multiline);
assert(await copyText(multiline,{clipboard:{writeText:async()=>{throw Error('Denied');}},document:doc}));assert(selected&&removed);assert.equal(area.value,multiline);
assert.equal(await copyText(multiline,{document:{...doc,execCommand:()=>false}}),false,'Manual copy must be offered when both mechanisms fail');
assert(!card({...prompts[0],title:'<img onerror=alert(1)>',exampleResult:'<script>x</script>'}).includes('<img'));
const root=new URL('../',import.meta.url),index=fs.readFileSync(new URL('prompts/index.html',root),'utf8'),sitemap=fs.readFileSync(new URL('sitemap.xml',root),'utf8');
assert(index.includes('16</strong> prompts'));assert(index.includes('14</strong> catégories'));assert(!index.includes('84 prompts'));
assert.equal((index.match(/class="pl-card"/g)||[]).length,16);
for(const p of prompts){
 const html=fs.readFileSync(new URL(`prompts/${p.slug}/index.html`,root),'utf8');
 assert(html.includes(escapeHTML(p.prompt)));assert(html.includes(escapeHTML(p.exampleResult)));
 assert(html.includes('Non testé avec un modèle IA'));assert(html.includes('id="pl-copy-example"'));
 assert.equal((html.match(/data-variable=/g)||[]).length,p.variables.length);
 assert(sitemap.includes(`https://elboubakry.com/prompts/${p.slug}/`));
 const schema=[...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)].flatMap(m=>JSON.parse(m[1]));
 assert.equal(schema[0]['@type'],'LearningResource');assert.equal(schema[0].text,p.prompt);
}
const browser=fs.readFileSync(new URL('assets/js/prompt-library.js',root),'utf8');
assert(!/\bfetch\s*\(|XMLHttpRequest/.test(browser),'Variables are never sent to an API');
assert(!/localStorage\.setItem.*values/.test(browser),'Variable values are not persisted');
console.log(`Prompt tests passed: ${prompts.length} unique prompts, ${categories.length} categories, distinct examples, routes/schema, filtering/sorting, URL state, escaping, repeated/empty variables and storage failure safety. Browser interaction QA is separate.`);
