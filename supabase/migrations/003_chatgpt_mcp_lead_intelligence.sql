create table if not exists public.analysis_batches (
  id uuid primary key default gen_random_uuid(),
  batch_code text not null unique,
  status text not null default 'queued',
  created_by text not null default 'crm',
  instructions text,
  total_leads integer not null default 0 check (total_leads >= 0),
  completed_leads integer not null default 0 check (completed_leads >= 0),
  failed_leads integer not null default 0 check (failed_leads >= 0),
  created_at timestamptz not null default now(),
  started_at timestamptz,
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint analysis_batches_status_check check (status in ('queued', 'processing', 'partial', 'completed', 'failed'))
);

create table if not exists public.analysis_batch_leads (
  id uuid primary key default gen_random_uuid(),
  batch_id uuid not null references public.analysis_batches(id) on delete cascade,
  lead_id uuid not null references public.leads(id) on delete cascade,
  status text not null default 'awaiting_chatgpt',
  error_message text,
  queued_at timestamptz not null default now(),
  started_at timestamptz,
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  unique (batch_id, lead_id),
  constraint analysis_batch_leads_status_check check (status in ('awaiting_chatgpt', 'in_progress', 'completed', 'failed'))
);

