create or replace view public.lead_intelligence_overview
with (security_invoker = true)
as
select
  l.*,
  coalesce(a.analysis_status, 'not_analyzed') as analysis_status,
  a.digital_maturity_score,
  a.opportunity_score,
  a.sales_priority_score,
  a.research_confidence,
  a.current_situation,
  a.website_analysis,
  a.landing_page_analysis,
  a.seo_analysis,
  a.geo_analysis,
  a.social_analysis,
  a.marketing_analysis,
  a.crm_automation_analysis,
  a.score_explanations,
  a.weaknesses,
  a.opportunities,
  a.recommended_services,
  a.action_plan,
  a.sales_approach,
  a.evidence,
  a.report_markdown,
  a.researched_at,
  a.research_source,
  a.error_message,
  a.updated_at as analysis_updated_at,
  latest_batch.batch_id,
  latest_batch.batch_code,
  latest_batch.batch_lead_status
from public.leads l
left join public.lead_analyses a on a.lead_id = l.id
left join lateral (
  select abl.batch_id, ab.batch_code, abl.status as batch_lead_status
  from public.analysis_batch_leads abl
  join public.analysis_batches ab on ab.id = abl.batch_id
  where abl.lead_id = l.id
  order by abl.queued_at desc
  limit 1
) latest_batch on true;

revoke all on public.lead_intelligence_overview from anon, authenticated;
grant select on public.lead_intelligence_overview to service_role;

create or replace function public.prepare_analysis_batch(
  p_batch_code text,
  p_lead_ids uuid[],
  p_created_by text default 'crm',
  p_instructions text default null
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_batch public.analysis_batches;
  v_count integer;
begin
  if coalesce(array_length(p_lead_ids, 1), 0) = 0 then
    raise exception 'At least one lead is required';
  end if;

  insert into public.analysis_batches (batch_code, created_by, instructions)
  values (p_batch_code, left(coalesce(nullif(p_created_by, ''), 'crm'), 160), left(p_instructions, 4000))
  returning * into v_batch;

  insert into public.analysis_batch_leads (batch_id, lead_id)
  select v_batch.id, l.id
  from public.leads l
  where l.id = any(p_lead_ids)
  on conflict (batch_id, lead_id) do nothing;

  get diagnostics v_count = row_count;
  if v_count = 0 then raise exception 'No valid leads found'; end if;

  update public.analysis_batches set total_leads = v_count where id = v_batch.id;

  insert into public.lead_analyses (lead_id, analysis_status, research_source, error_message)
  select abl.lead_id, 'queued', 'chatgpt_mcp', null
  from public.analysis_batch_leads abl
  where abl.batch_id = v_batch.id
  on conflict (lead_id) do update set
    analysis_status = 'queued', research_source = 'chatgpt_mcp', error_message = null, updated_at = now();

  return jsonb_build_object('id', v_batch.id, 'batch_code', v_batch.batch_code, 'total_leads', v_count, 'status', 'queued');
end;
$$;

revoke all on function public.prepare_analysis_batch(text, uuid[], text, text) from public, anon, authenticated;
grant execute on function public.prepare_analysis_batch(text, uuid[], text, text) to service_role;
